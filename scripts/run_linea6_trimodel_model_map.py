def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def case_slug(path: Path) -> str:
    return path.stem.replace("seed_", "").replace("assembled_", "").lower()


def read_json(path: Path) -> Dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def model_layer(model: RouteModel, *, temperature: float = 0.7) -> Dict[str, Any]:
    return {
        "provider": model.provider,
        "model": model.model,
        "base_url": model.base_url,
        "base_url_env": model.base_url_env,
        "api_key_env": model.api_key_env,
        "temperature": temperature,
        "seed": None,
    }


def sorted_agent_ids(agent_configs: Sequence[Dict[str, Any]]) -> List[int]:
    ids: List[int] = []
    for idx, cfg in enumerate(agent_configs):
        ids.append(int(cfg.get("agent_id", idx)))
    return sorted(ids)


def build_round_robin_model_map(agent_configs: Sequence[Dict[str, Any]]) -> Dict[str, Any]:
    """Deterministically assign sorted agent_ids Qwen, Gemma, Llama, repeat."""
    by_agent_id: Dict[int, Dict[str, Any]] = {}
    for pos, agent_id in enumerate(sorted_agent_ids(agent_configs)):
        by_agent_id[agent_id] = model_layer(ROUTE_MODELS[pos % len(ROUTE_MODELS)])
    return {
        "version": 1,
        "default": model_layer(ROUTE_MODELS[0]),
        "fallback": {"enabled": False},
        "by_agent_id": by_agent_id,
    }


def write_model_map(path: Path, model_map: Dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(yaml.safe_dump(model_map, sort_keys=False, allow_unicode=True), encoding="utf-8")


def synthetic_agent_configs(n: int = 12) -> List[Dict[str, Any]]:
    roles = [
        "PollingInstitution",
        "Organization",
        "MediaOutlet",
        "GovernmentExecutive",
        "FiscalConsultancy",
        "Person",
    ]
    return [
        {
            "agent_id": i,
            "entity_type": roles[i % len(roles)],
            "active_hours": list(range(8, 23)),
            "activity_level": 0.75,
        }
        for i in range(n)
    ]


def load_agent_configs_from_sim_dir(sim_dir: Path) -> List[Dict[str, Any]]:
    config_path = sim_dir / "simulation_config.json"
    if not config_path.exists():
        raise FileNotFoundError(f"simulation_config.json not found in {sim_dir}")
    config = read_json(config_path)
    agent_configs = config.get("agent_configs") or []
    if not agent_configs:
        profiles_path = sim_dir / "reddit_profiles.json"
        if profiles_path.exists():
            profiles = json.loads(profiles_path.read_text(encoding="utf-8"))
            agent_configs = [
                {"agent_id": i, "entity_type": p.get("entity_type") or p.get("role")}
                for i, p in enumerate(profiles)
            ]
    if not agent_configs:
        raise ValueError(f"No agent_configs or reddit_profiles.json agents found in {sim_dir}")
    return agent_configs


def route_audit_from_map(map_path: Path, agent_configs: Sequence[Dict[str, Any]]) -> List[Dict[str, Any]]:
    router = ModelRouter(load_model_map(str(map_path)))
    roles = {int(cfg.get("agent_id", idx)): cfg.get("entity_type") for idx, cfg in enumerate(agent_configs)}
    return [router.resolve(agent_id, roles.get(agent_id)).to_audit() for agent_id in sorted_agent_ids(agent_configs)]


def write_jsonl(path: Path, rows: Iterable[Dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        for row in rows:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")


def parse_jsonl(path: Path) -> List[Dict[str, Any]]:
    if not path.exists():
        return []
    rows: List[Dict[str, Any]] = []
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        line = line.strip()
        if not line:
            continue
        rows.append(json.loads(line))
    return rows


def summarize_telemetry(telemetry_path: Path) -> Dict[str, Any]:
    rows = parse_jsonl(telemetry_path)
    by_model: Dict[str, Dict[str, Any]] = defaultdict(lambda: {"calls": 0, "tokens_in": 0, "tokens_out": 0, "errors": 0})
    providers: set[str] = set()
    errors = 0
    parse_errors = 0
    for rec in rows:
        model = rec.get("model") or "unknown"
        providers.add(str(rec.get("provider") or "unknown"))
        slot = by_model[model]
        slot["calls"] += 1
        slot["tokens_in"] += int(rec.get("tokens_in") or 0)
        slot["tokens_out"] += int(rec.get("tokens_out") or 0)
        if rec.get("error"):
            errors += 1
            slot["errors"] += 1
        if rec.get("output_valid_json") is False:
            parse_errors += 1
    return {
        "llm_calls": len(rows),
        "tokens_in": sum(v["tokens_in"] for v in by_model.values()),
        "tokens_out": sum(v["tokens_out"] for v in by_model.values()),
        "errors": errors,
        "parse_errors": parse_errors,
        "models": sorted(m for m in by_model if m != "unknown"),
        "providers": sorted(providers),
        "by_model": dict(sorted(by_model.items())),
    }


def validate_effective_trimodel(audit_path: Path, telemetry_path: Path) -> Dict[str, Any]:
    audit_rows = parse_jsonl(audit_path)
    telemetry_summary = summarize_telemetry(telemetry_path)
    assigned = {row.get("model") for row in audit_rows if row.get("model")}
    called = set(telemetry_summary["models"])
    return {
        "expected_models": sorted(EXPECTED_MODELS),
        "assigned_models": sorted(assigned),
        "called_models": sorted(called),
        "missing_assigned_models": sorted(EXPECTED_MODELS - assigned),
        "missing_called_models": sorted(EXPECTED_MODELS - called),
        "is_assigned_trimodel": EXPECTED_MODELS.issubset(assigned),
        "is_effective_trimodel": EXPECTED_MODELS.issubset(called),
        "telemetry_summary": telemetry_summary,
    }



def start_backend(env: Dict[str, str], out: Path) -> subprocess.Popen[str]:
    out.mkdir(parents=True, exist_ok=True)
    return subprocess.Popen(
        [str(PY), "backend/run.py"],
        cwd=REPO,
        env=env,
        stdout=(out / "backend_stdout.log").open("w", encoding="utf-8"),
        stderr=(out / "backend_stderr.log").open("w", encoding="utf-8"),
        text=True,
        start_new_session=(os.name != "nt"),
        creationflags=subprocess.CREATE_NEW_PROCESS_GROUP if os.name == "nt" else 0,
    )


def stop_backend_process(proc: subprocess.Popen[str]) -> None:
    if proc.poll() is not None:
        return
    if os.name == "nt":
        proc.terminate()
        try:
            proc.wait(timeout=10)
        except subprocess.TimeoutExpired:
            proc.kill()
        return

    try:
        os.killpg(proc.pid, signal.SIGTERM)
    except ProcessLookupError:
        return
    try:
        proc.wait(timeout=10)
    except subprocess.TimeoutExpired:
        try:
            os.killpg(proc.pid, signal.SIGKILL)
        except ProcessLookupError:
            pass


def wait_backend(base_url: str, timeout: int = 90) -> None:
    client = APIClient(base_url, Path(os.devnull), timeout_seconds=5)
    deadline = time.time() + timeout
    last: Optional[Exception] = None
    while time.time() < deadline:
        try:
            client.request_json("GET", "/health")
            return
        except Exception as exc:  # noqa: BLE001
            last = exc
            time.sleep(1)
    raise TimeoutError(f"backend did not become ready at {base_url}: {last}")


def wait_graph_task(client: APIClient, task_id: str, timeout: int, poll_interval: float) -> Dict[str, Any]:
    deadline = time.time() + timeout
    while time.time() < deadline:
        resp = client.request_json("GET", f"/api/graph/task/{task_id}")
        task = resp.get("data", {})
        status = task.get("status")
        if status in TERMINAL_TASK_STATUSES:
            if status != "completed":
                raise RuntimeError(f"graph task ended with status {status}: {task}")
            return task
        time.sleep(poll_interval)
    raise TimeoutError("graph task polling timed out")


def wait_prepare(client: APIClient, simulation_id: str, task_id: Optional[str], timeout: int, poll_interval: float) -> Dict[str, Any]:
    deadline = time.time() + timeout
    while time.time() < deadline:
        payload: Dict[str, Any] = {"simulation_id": simulation_id}
        if task_id:
            payload["task_id"] = task_id
        resp = client.request_json("POST", "/api/simulation/prepare/status", payload)
        task = resp.get("data", {})
        status = task.get("status")
        if status in {"ready", "completed"}:
            return task
        if status in {"failed", "cancelled", "error"}:
            raise RuntimeError(f"prepare ended with status {status}: {task}")
        time.sleep(poll_interval)
    raise TimeoutError("prepare polling timed out")


def wait_run(client: APIClient, simulation_id: str, timeout: int, poll_interval: float) -> Dict[str, Any]:
    deadline = time.time() + timeout
    last: Dict[str, Any] = {}
    while time.time() < deadline:
        resp = client.request_json("GET", f"/api/simulation/{simulation_id}/run-status")
        last = resp.get("data", {})
        status = last.get("runner_status")
        if status in TERMINAL_RUN_STATUSES:
            return last
        time.sleep(poll_interval)
    raise TimeoutError(f"simulation run polling timed out; last={last}")


def run_entropy(sim_dir: Path, label: str, out: Path) -> Dict[str, Any]:
    commands = {
        "pooled": [str(PY), "backend/scripts/entropy_phase2_analysis.py", "--sim-dir", str(sim_dir), "--label", f"{label}-trimodel-pooled", "--with-embeddings", "--real-embedder", "--output", str(out / f"phase2_{label}_trimodel_pooled.json")],
        "postsonly": [str(PY), "backend/scripts/entropy_phase2_analysis.py", "--sim-dir", str(sim_dir), "--label", f"{label}-trimodel-postsonly", "--with-embeddings", "--real-embedder", "--no-comments", "--output", str(out / f"phase2_{label}_trimodel_postsonly.json")],
    }
    result = {}
    for name, cmd in commands.items():
        cp = subprocess.run(cmd, cwd=REPO, text=True, capture_output=True, timeout=1800)
        (out / f"entropy_{name}.stdout.log").write_text(cp.stdout, encoding="utf-8")
        (out / f"entropy_{name}.stderr.log").write_text(cp.stderr, encoding="utf-8")
        result[name] = {"exit_code": cp.returncode, "command": cmd, "output": cmd[-1]}
    return result


def execute_case(args: argparse.Namespace, client: APIClient, case_file: Path, out: Path) -> Dict[str, Any]:
    out.mkdir(parents=True, exist_ok=True)
    started_at = utc_now()
    ontology = client.post_multipart(
        "/api/graph/ontology/generate",
        fields={"simulation_requirement": args.requirement, "project_name": f"Linea6 trimodel {case_slug(case_file)}"},
        files=[case_file],
        retry=True,
        max_retries=3,
    )
    project_id = ontology.get("data", {}).get("project_id")
    if not project_id:
        raise RuntimeError(f"ontology/generate did not return project_id: {ontology}")
    graph_payload: Dict[str, Any] = {"project_id": project_id}
    if args.graph_chunk_size:
        graph_payload["chunk_size"] = args.graph_chunk_size
    graph_build = client.request_json("POST", "/api/graph/build", graph_payload, retry=True)
    graph_task_id = graph_build.get("data", {}).get("task_id")
    wait_graph_task(client, graph_task_id, args.poll_timeout, args.poll_interval)
    project = client.request_json("GET", f"/api/graph/project/{project_id}")
    graph_id = project.get("data", {}).get("graph_id")
    create = client.request_json("POST", "/api/simulation/create", {"project_id": project_id, "graph_id": graph_id, "enable_twitter": True, "enable_reddit": True}, retry=True)
    simulation_id = create.get("data", {}).get("simulation_id")
    prepare = client.request_json("POST", "/api/simulation/prepare", {"simulation_id": simulation_id, "use_llm_for_profiles": True, "parallel_profile_count": args.parallel_profile_count}, retry=True)
    wait_prepare(client, simulation_id, prepare.get("data", {}).get("task_id"), args.poll_timeout, args.poll_interval)

    sim_dir = REPO / "backend/uploads/simulations" / simulation_id
    agent_configs = load_agent_configs_from_sim_dir(sim_dir)
    model_map = build_round_robin_model_map(agent_configs)
    sim_map = sim_dir / "model_map_linea6_trimodel.generated.yaml"
    out_map = out / "model_map.generated.yaml"
    write_model_map(sim_map, model_map)
    write_model_map(out_map, model_map)

    start_payload = {
        "simulation_id": simulation_id,
        "platform": "reddit",
        "force": True,
        "enable_graph_memory_update": False,
        "no_wait": True,
        "max_rounds": args.rounds,
        "model_map_path": str(sim_map),
    }
    client.request_json("POST", "/api/simulation/start", start_payload, retry=True)
    final_run = wait_run(client, simulation_id, args.poll_timeout, args.poll_interval)

    audit_path = sim_dir / "model_routing_audit.jsonl"
    telemetry_path = sim_dir / "llm_telemetry.jsonl"
    summary_path = out / "llm_telemetry_summary.json"
    validation = validate_effective_trimodel(audit_path, telemetry_path)
    write_json(summary_path, validation["telemetry_summary"])
    write_json(out / "trimodel_validation.json", validation)
    for artifact in [audit_path, telemetry_path, sim_dir / "simulation.log", sim_dir / "reddit_simulation.db", sim_dir / "simulation_config.json", sim_dir / "reddit_profiles.json"]:
        if artifact.exists():
            shutil.copy2(artifact, out / artifact.name)
    entropy = {}
    if final_run.get("runner_status") == "completed" and telemetry_path.exists():
        entropy = run_entropy(sim_dir, case_slug(case_file), out)
    manifest = {
        "started_at": started_at,
        "completed_at": utc_now(),
        "case_file": str(case_file),
        "project_id": project_id,
        "graph_id": graph_id,
        "simulation_id": simulation_id,
        "sim_dir": str(sim_dir),
        "rounds_requested": args.rounds,
        "final_run": final_run,
        "model_map_path": str(sim_map),
        "is_assigned_trimodel": validation["is_assigned_trimodel"],
        "is_effective_trimodel": validation["is_effective_trimodel"],
        "entropy": entropy,
    }
    write_json(out / "run_manifest.json", manifest)
    return manifest


def execute(args: argparse.Namespace, out_root: Path) -> int:
    require_execute_keys()
    out_root.mkdir(parents=True, exist_ok=True)
    backend_proc: Optional[subprocess.Popen[str]] = None
    try:
        if args.start_backend:
            env = backend_env()
            write_json(
                out_root / "backend_env_sanitized.json",
                {
                    "LLM_MODEL_NAME": env.get("LLM_MODEL_NAME"),
                    "LLM_BASE_URL": env.get("LLM_BASE_URL"),
                    "GRAPHITI_LLM_MODEL": env.get("GRAPHITI_LLM_MODEL"),
                    "GRAPHITI_LLM_BASE_URL": env.get("GRAPHITI_LLM_BASE_URL"),
                    "OASIS_SEMAPHORE": env.get("OASIS_SEMAPHORE"),
                    "OPENROUTER_API_KEY": "<set>" if env.get("OPENROUTER_API_KEY") else "<unset>",
                    "DEEPINFRA_API_KEY": "<set>" if env.get("DEEPINFRA_API_KEY") else "<unset>",
                },
            )
            backend_proc = start_backend(env, out_root)
            wait_backend(args.base_url, timeout=120)
        client = APIClient(args.base_url, out_root / "request_trace.json", timeout_seconds=300, accept_language="es")
        manifests = []
        for case_file in expand_cases(args):
            manifests.append(execute_case(args, client, case_file, out_root / case_slug(case_file)))
            write_json(out_root / "summary.json", {"mode": "execute", "results": manifests})
        ok = all(m.get("is_effective_trimodel") for m in manifests)
        return 0 if ok else 2
    finally:
        if backend_proc is not None:
            stop_backend_process(backend_proc)


def expand_cases(args: argparse.Namespace) -> List[Path]:
    if args.all_temporal_packs:
        names = ["seed_T0.md", "seed_T1.md", "seed_T2.md", "seed_T3.md", "seed_T3_clean.md"]
        return [DEFAULT_CASE_DIR / name for name in names]
    return [Path(p).resolve() for p in (args.case_file or [DEFAULT_CASE])]


